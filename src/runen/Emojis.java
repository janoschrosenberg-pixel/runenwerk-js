    /** alle Emojis in der Reihenfolge der Liste (ohne Aliase) */
    static final List<Emoji> ALLE = new ArrayList<>();
    /** Name und Aliase -> Zeichen */
    static final Map<String, String> NACH_NAME = new HashMap<>();
    /** Name -> Aliase (fuer die Suche) */
    static final Map<String, List<String>> ALIASE = new HashMap<>();

    static {
        for (String[] d : DATEN) {
            ALLE.add(new Emoji(d[0], d[1]));
            List<String> a = new ArrayList<>();
            for (int i = 0; i < d.length; i++) {
                if (i == 1) continue;
                NACH_NAME.put(d[i], d[1]);
                if (i > 1) a.add(d[i]);
            }
            ALIASE.put(d[0], a);
        }
    }

    /** Wertung fuer die Suche: 3 Name beginnt mit q, 2 ein Wortteil oder Alias beginnt mit q, 1 enthaelt q, -1 passt nicht */
    static int wertung(Emoji e, String q) {
        if (q.isEmpty()) return 0;
        String n = e.name();
        if (n.startsWith(q)) return 3;
        for (String t : n.split("[_-]")) if (t.startsWith(q)) return 2;
        for (String a : ALIASE.getOrDefault(n, List.of())) if (a.startsWith(q)) return 2;
        if (n.contains(q)) return 1;
        for (String a : ALIASE.getOrDefault(n, List.of())) if (a.contains(q)) return 1;
        return -1;
    }

    private static final Pattern KURZ = Pattern.compile(":([a-z0-9_+\\-]+):");

    /** :name: durch das Zeichen ersetzen, wenn es den Namen gibt (eigene Emojis des Servers bleiben stehen) */
    static String ersetzen(String s) {
        if (s == null || s.indexOf(':') < 0) return s;
        Matcher m = KURZ.matcher(s);
        StringBuilder b = new StringBuilder();
        while (m.find()) {
            String z = NACH_NAME.get(m.group(1));
            m.appendReplacement(b, Matcher.quoteReplacement(z != null ? z : m.group()));
        }
        m.appendTail(b);
        return b.toString();
    }

    /** Zeichen eines Namens (auch Alias) oder null */
    static String zeichen(String name) {
        return NACH_NAME.get(name);
    }
